/* 核心标签 = 第 19 轮之前就存在的 41 个。长尾覆写只用在「选词池」上。 */
const CORE_TAGS = THREAD_TAGS.slice(0, 41);
/* 核心内部按「名次越靠前越容易被挂上」加权（1/√rank，温和的齐普夫）。
   不这样做的话，201 个标签会让每个标签都分到差不多多的帖（864 ÷ 201 ≈ 4），
   首页那条「尾巴越长越热」就成了一条几乎等长的尺子 —— 数据是假的，长度轴也就没意义。 */
const CORE_W = (() => {
  const w = CORE_TAGS.map((_, i) => 1 / Math.sqrt(i + 1));
  const s = w.reduce((a, b) => a + b, 0);
  return w.map((x) => x / s);
})();
function pickCore(u) {
  let acc = 0;
  for (let i = 0; i < CORE_W.length; i++) { acc += CORE_W[i]; if (u < acc) return CORE_TAGS[i]; }
  return CORE_TAGS[CORE_TAGS.length - 1];
}

/* 覆写 longTailTags（**追加版**，函数名与原来相同，后定义者生效）：
   结构、随机流消耗顺序、want 的分布（62% 不挂 / 30% 挂 1~6 个 / 8% 挂 18~28 个）
   全部与原来一致；变化只有选词：
     · 72% 从核心 41 个里按 1/√rank 加权抽（越靠前越热）；
     · 28% 从全表 201 个里按步长抽（新标签以细分姿态出现）。
   于是核心标签仍然热、而且彼此拉得开；新标签均匀落在长尾上。
   ⚠️ 这里多消耗了 r()（选池子 / 加权抽签），但每个 seed 的流都是独立的，不会串到别的帖。 */
function longTailTags(have, seed) {
  const r = threadRng(seed);
  const u = r();
  const want = u < .62 ? 0 : u < .92 ? 1 + Math.floor(r() * 6) : 18 + Math.floor(r() * 11);
  if (!want) return have;
  const set = new Set(have);
  const cap = Math.min(THREAD_TAGS.length, have.length + want);
  let k = Math.floor(r() * THREAD_TAGS.length);
  let guard = 0;
  while (set.size < cap && guard++ < 500) {
    const useCore = r() < .72;
    set.add(useCore ? pickCore(r()) : THREAD_TAGS[k % THREAD_TAGS.length]);
    k += 1 + Math.floor(r() * 4);
  }
  return [...set];
}
