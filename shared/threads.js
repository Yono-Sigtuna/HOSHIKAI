/* 长尾标签：给一条帖子按**独立种子**补挂若干标签。
   ⚠️⚠️ 必须独立于 makeThread 的主 rnd 流 —— 那条流是按顺序消费字段的，
   在这里多拿一个数就会把后面的 replies / views / mins / postedMins 全部平移，
   整个板块的帖子内容都会变（前缀稳定性也没了）。
   `have` 的顺序就是最终顺序，所以**首标签（板块页卡片展示的那一个）永远是头一个**，卡片不受影响。
   分布：约 62% 维持 1~2 个，约 30% 挂到 3~8 个，约 8% 挂到 20~30 个
   —— 用户问的「一个帖子 20~30 个 TAG」就是这一档。 */
function longTailTags(have, seed) {
  const r = threadRng(seed);
  const u = r();
  const want = u < .62 ? 0 : u < .92 ? 1 + Math.floor(r() * 6) : 18 + Math.floor(r() * 11);
  if (!want) return have;
  const set = new Set(have);
  const cap = Math.min(THREAD_TAGS.length, have.length + want);
  let k = Math.floor(r() * THREAD_TAGS.length);
  let guard = 0;
  while (set.size < cap && guard++ < 500) {
    set.add(THREAD_TAGS[k % THREAD_TAGS.length]);
    k += 1 + Math.floor(r() * 4);
  }
  return [...set];
}

