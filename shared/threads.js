/* ---------- 标签热度（追加函数，第 22 轮）----------
   全站 12 个子板块的帖池里，每个标签挂了多少帖。
   ⚠️ 首页（热门 TAG 流星带）和帖内页（本帖标签带）要的是**同一个数** —— 同一个标签
   在两个页面必须一样长，否则那条长度轴就是假的。所以统计只能有一份，放在这里。
   ⚠️ 这是**追加**：不改任何既有名字（shared/*.js 只可追加，四个版本共用本文件）。 */
function tagHeat() {
  const cnt = new Map();
  FORUM.boards.forEach((b, bi) => b.sections.forEach((_, si) => {
    boardThreads(bi, si, THREAD_POOL_SIZE).forEach((t) => {
      (t.tags || []).forEach((g) => cnt.set(g, (cnt.get(g) || 0) + 1));
    });
  }));
  const rows = [...cnt].sort((a, b) => b[1] - a[1]);
  const maxN = rows[0][1], minN = rows[rows.length - 1][1];
  const spread = Math.max(1, maxN - minN);
  const total = rows.reduce((s, [, n]) => s + n, 0);
  /* tag 热度 → 星等：沿用站里 magnitude() 那条 0.6–6.5 的标度，映射到 0.8–5.5
     （实测与站内数量级一致：最热的标签 0.8 等，正好是页脚星等图例的「爆帖」档）。
     ⚠️ 长度轴必须走这条**归一化**的标度：真实帖数 64→39 画出来几乎一样长，
        差异会被抹平。它是归一化的（约 5.7 倍），不是真实比例 —— 页面上写明了。 */
  const toMag = (n) => +(0.8 + (maxN - n) / spread * 4.7).toFixed(1);
  const of = new Map(rows);
  /* 查不到的标签（理论上不会有）回落到最冷的一档，绝不落到 toMag(0) —— 那会跑出标度外 */
  const countOf = (g) => (of.has(g) ? of.get(g) : minN);
  const glowOf = (g) => magnitudeGlow(toMag(countOf(g)));
  return {
    rows, total, countOf, toMag, glowOf,
    width: (g) => 9 + glowOf(g) * 33,
  };
}


